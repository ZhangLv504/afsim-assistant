from __future__ import annotations

import json
import re
import shutil
from datetime import datetime, timezone
from pathlib import Path

from .config import Settings


class BuildError(RuntimeError):
    pass


SUPPORTED_ROLES = {"air_defense_site", "aircraft"}
REQUIRED_CAPABILITIES = {"detection", "tracking", "weapon_engagement"}


def _safe_slug(value: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9_-]+", "_", str(value or "").strip()).strip("_-").lower()
    if not slug:
        raise BuildError("scenario name does not contain a safe file-name character")
    return slug[:80]


def _duration_seconds(duration: dict | None) -> int:
    if duration is None:
        return 1200
    value = float(duration["value"])
    factors = {"seconds": 1, "minutes": 60, "hours": 3600}
    seconds = round(value * factors[duration["unit"]])
    if seconds <= 0:
        raise BuildError("scenario duration must be positive")
    return seconds


def supports_sam_air_intercept(spec: dict) -> tuple[bool, list[str]]:
    problems = []
    forces = spec.get("forces") or []
    roles = {force.get("role") for force in forces}
    if len(forces) != 2 or roles != SUPPORTED_ROLES:
        problems.append("first prototype requires exactly one air_defense_site and one aircraft force")
    if any(int(force.get("count") or 0) != 1 for force in forces):
        problems.append("first prototype supports one platform per force")
    missing = REQUIRED_CAPABILITIES - set(spec.get("capabilities") or [])
    if missing:
        problems.append("missing required capabilities: " + ", ".join(sorted(missing)))
    return not problems, problems


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.replace("\r\n", "\n"), encoding="utf-8", newline="\n")


def _write_json(path: Path, payload: dict) -> None:
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    temporary.replace(path)


def build_sam_air_intercept(
    settings: Settings,
    spec: dict,
    *,
    scenario_id: str | None = None,
) -> dict:
    supported, problems = supports_sam_air_intercept(spec)
    if not supported:
        raise BuildError("; ".join(problems))

    source = settings.demos_root / "launcher"
    if not (source / "setup.txt").is_file():
        raise BuildError(f"official launcher demo not found: {source}")
    slug = _safe_slug(scenario_id or spec["scenario_name"])
    target = settings.staging_dir / slug
    if target.exists():
        raise BuildError(f"staging project already exists: {target}")
    settings.staging_dir.mkdir(parents=True, exist_ok=True)
    shutil.copytree(
        source,
        target,
        ignore=shutil.ignore_patterns("output", "*.aer", "*.evt", "*.log"),
    )
    (target / "output").mkdir(exist_ok=True)

    seconds = _duration_seconds(spec.get("duration"))
    case_name = slug
    entry = target / "generated_main.txt"
    scenario = target / "scenarios" / "generated_scenario.txt"

    _write_text(
        entry,
        f"""# Generated by AFSIM Local Assistant from the official launcher demo.
define_path_variable CASE {case_name}
log_file output/$(CASE).log

include platforms/tactics_processor1.txt
include setup.txt
include scenarios/generated_scenario.txt

event_output
   file output/$(CASE).evt
   enable SENSOR_DETECTION_ATTEMPT
   enable SENSOR_TRACK_INITIATED
   enable SENSOR_TRACK_UPDATED
   enable LOCAL_TRACK_INITIATED
   enable LOCAL_TRACK_UPDATED
end_event_output
event_pipe file output/$(CASE).aer end_event_pipe

end_time {seconds} sec
""",
    )
    _write_text(
        scenario,
        """# Generated instance laydown. Types come from the copied official launcher demo.
platform red_aircraft AIRPLANE
   side red
   icon C-130
   indestructible
   route
      position 35:32n 76:01w altitude 4000 ft msl
         linear_acceleration 0.20 g
      position 35:32n 76:53w altitude 5000 ft msl
         speed 175 kts
   end_route
   commander SELF
end_platform

platform blue_sam_site SAM_LAUNCHER
   side blue
   icon SA-11_Launcher
   position 35:32n 76:13w altitude 0 ft msl
   heading 0 deg
   commander SELF
end_platform
""",
    )

    manifest = {
        "schema_version": 1,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "status": "staging",
        "template": {
            "id": "official.launcher.1st_run",
            "source": str(source),
            "entry_reference": "1st_run.txt",
        },
        "generated_entry": str(entry),
        "scenario_spec": spec,
        "selected_context_types": {
            "air_defense_site": "SAM_LAUNCHER",
            "aircraft": "AIRPLANE",
            "note": "These names are valid inside the copied launcher demo context; they are not selected from a global name alone.",
        },
        "assumptions": [
            "The official launcher geometry is adjusted so the aircraft enters radar range within the requested duration.",
            "One blue SAM site engages one indestructible red aircraft.",
            "The first official tactics processor is used for autonomous detection, tracking and firing.",
        ],
        "validation": None,
    }
    manifest_path = target / "ASSISTANT_MANIFEST.json"
    _write_json(manifest_path, manifest)
    return {
        "project_dir": str(target),
        "entry_file": str(entry),
        "manifest_path": str(manifest_path),
        "manifest": manifest,
    }


def record_validation(build: dict, result: dict) -> dict:
    manifest_path = Path(build["manifest_path"])
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["status"] = "validated" if result.get("ok") else "validation_failed"
    output_summary = result.get("outputs") or {}
    manifest["validation"] = {
        "recorded_at": datetime.now(timezone.utc).isoformat(),
        "ok": bool(result.get("ok")),
        "returncode": result.get("returncode"),
        "simulation_complete": result.get("simulation_complete"),
        "inert_simulation": result.get("inert_simulation"),
        "problems": result.get("problems") or [],
        "caveats": result.get("caveats") or [],
        "evt_events": output_summary.get("evt_events"),
        "evt_categories": output_summary.get("evt_categories") or {},
        "capability_evidence": result.get("capability_evidence") or {},
    }
    _write_json(manifest_path, manifest)
    validation_path = manifest_path.parent / "VALIDATION.json"
    _write_json(validation_path, result)
    return {
        **build,
        "manifest": manifest,
        "validation_path": str(validation_path),
        "validation": result,
    }


CAPABILITY_EVENTS = {
    "detection": {
        "SENSOR_TRACK_INITIATED",
        "LOCAL_TRACK_INITIATED",
    },
    "tracking": {
        "SENSOR_TRACK_INITIATED",
        "SENSOR_TRACK_UPDATED",
        "LOCAL_TRACK_INITIATED",
        "LOCAL_TRACK_UPDATED",
    },
    "weapon_engagement": {"WEAPON_FIRED"},
}


def enforce_capability_evidence(spec: dict, result: dict) -> dict:
    checked = dict(result)
    checked["problems"] = list(result.get("problems") or [])
    categories = (result.get("outputs") or {}).get("evt_categories") or {}
    evidence = {}
    for capability in spec.get("capabilities") or []:
        accepted = CAPABILITY_EVENTS.get(capability)
        if not accepted:
            continue
        observed = {name: int(categories.get(name) or 0) for name in sorted(accepted)}
        satisfied = any(count > 0 for count in observed.values())
        evidence[capability] = {"satisfied": satisfied, "events": observed}
        if not satisfied:
            checked["problems"].append(
                f"required capability has no event evidence: {capability}"
            )
    checked["capability_evidence"] = evidence
    checked["ok"] = bool(result.get("ok")) and not checked["problems"]
    checked["validated"] = checked["ok"]
    return checked

